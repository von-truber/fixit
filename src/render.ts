// JSON result to DOM. Every model string goes in via textContent, never innerHTML.
import type { DigestResponse, ExplainResponse } from "../shared/schema.ts";

type Child = Node | string | null | undefined | false;

export function el<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  attrs: Record<string, string> = {},
  ...children: Child[]
): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs)) {
    if (key === "class") node.className = value;
    else node.setAttribute(key, value);
  }
  for (const child of children) {
    if (child === null || child === undefined || child === false) continue;
    node.append(typeof child === "string" ? document.createTextNode(child) : child);
  }
  return node;
}

export async function copyText(text: string, button: HTMLButtonElement) {
  const original = button.textContent;
  try {
    await navigator.clipboard.writeText(text);
    button.textContent = "Copied";
  } catch {
    button.textContent = "Copy failed";
  }
  setTimeout(() => (button.textContent = original), 1500);
}

function copyButton(text: string, label: string, ariaLabel: string) {
  const button = el("button", { type: "button", class: "copy", "aria-label": ariaLabel }, label);
  button.addEventListener("click", () => copyText(text, button));
  return button;
}

const CONFIDENCE_LABEL = { high: "High", medium: "Medium", low: "Low" } as const;

function section(title: string, ...body: Child[]) {
  return el("section", { class: "result-section" }, el("h3", {}, title), ...body);
}

export function renderExplain(data: ExplainResponse): HTMLElement {
  const steps = el("ol", { class: "steps" });
  data.fix_steps.forEach((step, i) => {
    const li = el(
      "li",
      { class: step.dangerous ? "step dangerous" : "step" },
      el(
        "div",
        { class: "step-text" },
        step.dangerous && el("span", { class: "badge badge-danger" }, "⚠ Caution"),
        step.step,
      ),
    );
    if (step.command) {
      li.append(
        el(
          "div",
          { class: "command" },
          el("pre", {}, el("code", {}, step.command)),
          copyButton(step.command, "Copy", `Copy command for step ${i + 1}`),
        ),
      );
      if (step.dangerous) {
        li.append(
          el("p", { class: "danger-note" }, "This command can delete data, change permissions or needs admin rights. Read it before running it."),
        );
      }
    }
    steps.append(li);
  });

  return el(
    "article",
    { class: "result-card" },
    el(
      "header",
      { class: "result-header" },
      el("h2", { id: "result-title" }, data.summary),
      el(
        "span",
        { class: `badge badge-confidence confidence-${data.confidence}` },
        `Confidence: ${CONFIDENCE_LABEL[data.confidence]}`,
      ),
    ),
    section("What it means", el("p", {}, data.meaning)),
    data.causes.length > 0 &&
      section("Likely causes", el("ol", { class: "causes" }, ...data.causes.map((c) => el("li", {}, c)))),
    data.fix_steps.length > 0 && section("How to fix it", steps),
    data.verify && section("Check it worked", el("p", {}, data.verify)),
    el("p", { class: "detected" }, `Detected environment: ${data.detected_environment}`),
  );
}

export function explainToMarkdown(data: ExplainResponse): string {
  const lines = [`## ${data.summary}`, "", `**Confidence:** ${CONFIDENCE_LABEL[data.confidence]}`, "", "### What it means", "", data.meaning, ""];
  if (data.causes.length) {
    lines.push("### Likely causes", "", ...data.causes.map((c, i) => `${i + 1}. ${c}`), "");
  }
  if (data.fix_steps.length) {
    lines.push("### How to fix it", "");
    data.fix_steps.forEach((s, i) => {
      lines.push(`${i + 1}. ${s.dangerous ? "⚠ **Caution:** " : ""}${s.step}`);
      if (s.command) lines.push("", "   ```", `   ${s.command}`, "   ```");
    });
    lines.push("");
  }
  if (data.verify) lines.push("### Check it worked", "", data.verify, "");
  lines.push(`_Generated by Fixit. Suggestions may be wrong; check commands before running them._`);
  return lines.join("\n");
}

// ---------- Log Digest ----------

export type DigestIssue = DigestResponse["issues"][number];

const VERDICT = {
  healthy: { label: "Healthy", icon: "✓" },
  warnings: { label: "Warnings", icon: "!" },
  errors: { label: "Errors found", icon: "✕" },
} as const;

const SEVERITY = { error: "Error", warning: "Warning", info: "Info" } as const;

export function renderDigest(data: DigestResponse, onExplain: (issue: DigestIssue) => void): HTMLElement {
  const issues = el("ol", { class: "issues" });
  data.issues.forEach((issue) => {
    const explain = el("button", { type: "button", class: "secondary" }, "Explain this");
    explain.setAttribute("aria-label", `Explain this issue: ${issue.title}`);
    explain.addEventListener("click", () => onExplain(issue));
    issues.append(
      el(
        "li",
        { class: `issue severity-${issue.severity}` },
        el(
          "div",
          { class: "issue-head" },
          el("span", { class: `badge badge-severity sev-${issue.severity}` }, SEVERITY[issue.severity]),
          el("h4", {}, issue.title),
          el("span", { class: "issue-count" }, `×${issue.count.toLocaleString()}`),
        ),
        issue.first_seen && el("p", { class: "issue-meta" }, `First seen: ${issue.first_seen}`),
        el("pre", { class: "issue-sample" }, el("code", {}, issue.sample)),
        el("div", { class: "issue-actions" }, explain),
      ),
    );
  });

  const verdict = VERDICT[data.verdict];
  return el(
    "article",
    { class: "result-card" },
    el(
      "header",
      { class: "result-header" },
      el(
        "p",
        { class: `verdict verdict-${data.verdict}` },
        el("span", { class: "verdict-icon", "aria-hidden": "true" }, verdict.icon),
        `Verdict: ${verdict.label}`,
      ),
      el("h2", { id: "result-title" }, data.overview),
      el(
        "span",
        { class: `badge badge-confidence confidence-${data.confidence}` },
        `Confidence: ${CONFIDENCE_LABEL[data.confidence]}`,
      ),
    ),
    data.issues.length > 0 && section(`Top issues (${data.issues.length})`, issues),
    section("Probable root cause", el("p", {}, data.root_cause)),
    data.next_steps.length > 0 &&
      section("Next steps", el("ol", { class: "causes" }, ...data.next_steps.map((s) => el("li", {}, s)))),
  );
}

export function digestToMarkdown(data: DigestResponse): string {
  const lines = [
    `## Log digest: ${VERDICT[data.verdict].label}`,
    "",
    data.overview,
    "",
    `**Confidence:** ${CONFIDENCE_LABEL[data.confidence]}`,
    "",
  ];
  if (data.issues.length) {
    lines.push("### Top issues", "");
    data.issues.forEach((issue, i) => {
      const seen = issue.first_seen ? `, first seen ${issue.first_seen}` : "";
      lines.push(`${i + 1}. **${issue.title}** (${SEVERITY[issue.severity]}, ×${issue.count}${seen})`, "", "   ```", `   ${issue.sample}`, "   ```");
    });
    lines.push("");
  }
  lines.push("### Probable root cause", "", data.root_cause, "");
  if (data.next_steps.length) lines.push("### Next steps", "", ...data.next_steps.map((s, i) => `${i + 1}. ${s}`), "");
  lines.push(`_Generated by Fixit. The log may have been trimmed before analysis._`);
  return lines.join("\n");
}
